# Writes ludus-qt/qml/color.js from the full Ludus's own color code (renderer/look.js): text on a
# color, OKLCH, and the random pastel selector glow, word for word. Run it after look.js changes;
# test_color.py fails while the two differ.  python3 tools/ludus-qt-test/gen_color.py
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
LOOK = os.path.join(ROOT, 'system_files', 'usr', 'lib', 'tessera', 'launcher', 'renderer', 'look.js')
OUT = os.path.join(ROOT, 'system_files', 'usr', 'lib', 'tessera', 'ludus-qt', 'qml', 'color.js')
NAMES = ['lumOf', 'onColor', 'oklchRgb', 'inGamut', 'oklchHex', 'maxChroma', 'nextPastel']


def block(src, name):
    """The whole declaration of one function (or const arrow function), by brace counting."""
    m = re.search(r'^(function %s\b|const %s = )' % (name, name), src, re.M)
    if not m:
        sys.exit('look.js has no %s' % name)
    i = m.start()
    if src[m.end() - 3:m.end()] == ' = ' and '{' not in src[m.end():src.index('\n', m.end())]:
        return src[i:src.index('\n', m.end()) + 1]
    j = src.index('{', m.end())
    depth = 0
    for k in range(j, len(src)):
        depth += {'{': 1, '}': -1}.get(src[k], 0)
        if depth == 0:
            end = src.index('\n', k) + 1 if src.find('\n', k) >= 0 else len(src)
            return src[i:end]
    sys.exit('unbalanced %s' % name)


def generate():
    src = open(LOOK, encoding='utf-8').read()
    parts = [block(src, n) for n in NAMES]
    return ('// SPDX-License-Identifier: GPL-3.0-or-later\n'
            '// GENERATED by tools/ludus-qt-test/gen_color.py from launcher/renderer/look.js: do not edit.\n'
            '// The full Ludus\'s color code, word for word, for the Qt screens.\n'
            '.pragma library\n\nvar selHue = null; // the hue of the last pastel pick\n\n' + '\n'.join(parts))


if __name__ == '__main__':
    open(OUT, 'w', encoding='utf-8').write(generate())
    print('wrote', OUT)
